function out = simulate_task4_v3(p, opt)
% SIMULATE_TASK4_V3  V3 (DEVELOPMENT) copy of SIMULATE_TASK4_V2 with two further switches.
%   opt.v3_qp_exact          (default false) the two-row HOCBF-QP is solved by
%                            CBF_QP_TWO_ROW_V3 (exact active-set enumeration, recomputed KKT
%                            certificate, explicit fallback hierarchy). A fallback (level 1:
%                            capture row softened; level 2: best-effort push) is applied and
%                            recorded per step in out.v3, and the run continues; the hard
%                            problem is never reported as solved when it was not.
%   opt.v3_handoff_authority (default false) D9 handoff by HANDOFF_DETECTOR_V3: the V2
%                            reachable-boundary rule AND the actuator-authority gate
%                            a_req <= (1 - beta)*u_max. Requires v2_handoff_tightened = true.
%   With both V3 switches false the run is SIMULATE_TASK4_V2 (test T3). Generated by
%   make_simulate_v3.py; everything below is the V2 text unless marked V3.
%
% SIMULATE_TASK4_V2  V2 (EXPLORATORY) copy of the FROZEN simulate_task4 with two switches.
%   opt.v2_preview_online    (default false) re-anchor the MPC capture-point preview at
%                            every step on the measured (q, w) and the online theta_hat
%                            (CAPTURE_PREVIEW_ONLINE) instead of the open-loop table.
%   opt.v2_handoff_tightened (default false) D9 handoff on the reachable boundary of the
%                            tightened commitment row (HANDOFF_DETECTOR_V2).
%   With both switches false the run is the frozen simulate_task4 (test T1 checks this
%   bit for bit). The estimator step is moved before the MPC layer so that the preview
%   can use theta_hat(t_k); the estimator does not depend on the command, so this order
%   change is numerically neutral (T1). Generated by make_simulate_v2.py from the frozen
%   file; the frozen file is not modified. Everything below is the frozen text unless
%   marked V2.
%
% SIMULATE_TASK4  Closed loop: preview MPC + two-row adaptive HOCBF-QP + D9 handoff.
%   out = simulate_task4(p, opt) runs the frozen Task 4 architecture of
%   notes/task4_freeze_record.md:
%
%     x -> [reference preview] -> [MPC QP] -> u_mpc
%       -> [two-row HOCBF-QP: h_body + h_cap] -> u_safe -> plant
%
%   with the T4-D4 concurrent-learning estimator supplying theta_hat and nu to
%   the capture row's tightening, and the T4-D9 detector deciding handoff.
%
%   ROW SET OVER TIME (freeze record Sec. 8.2)
%     before a NORMAL handoff : h_body AND h_cap are both enforced
%     after  a NORMAL handoff : h_cap is PERMANENTLY disabled for the rest of the
%                               run; h_body continues to be enforced
%     on a GUARD_BREACH       : the run is marked FAILED and terminated cleanly;
%                               no handoff is latched and h_cap is NOT disabled
%                               as though a handoff had occurred
%
%   TASK 3 IS NOT TOUCHED. The reference preview, the MPC and the body barrier
%   are the frozen Task 3 components, called unmodified. This driver is additive.
%
%   opt.Tsim is REQUIRED. There is deliberately no default: the Task 4
%   demonstration horizon is explicitly unfrozen, so this function refuses to
%   choose one. The caller must supply it, and must never iterate it until a
%   handoff occurs.
%
%   opt fields (optional):
%     x0          initial state (default scenario)
%     alpha       D9 band parameter (default p.t4.alpha = 1e-3). Only members of
%                 the predeclared set p.t4.alpha_set are accepted; anything else
%                 is rejected. alpha is NOT FROZEN as a final value.
%     N           prediction horizon override
%     n_sub       intersample evaluation points per step (default 10)
%     targetEst   estimated target state for the MPC preview (default = truth)
%     allow_inadmissible_ic
%                 default FALSE. When false, a production run whose initial
%                 condition lies outside the applicable HOCBF admissible set is
%                 refused before any control step: it returns immediately with
%                 eligibility = 'INELIGIBLE_IC', d9_evaluated = false,
%                 event = 'NOT_EVALUATED' and guard_validation = 'N/A'.
%
%                 NOTE ON TAXONOMY. Refusal is a PRE-RUN VALIDATION-ELIGIBILITY
%                 status, NOT a D9 outcome. D9 remains frozen with exactly three
%                 outcomes - NORMAL, GUARD_BREACH, NO_EVENT - and a refused run
%                 has none of them, because the detector never ran. The marker
%                 'NOT_EVALUATED' records that absence; it must never be counted,
%                 reported or reasoned about as a fourth D9 outcome.
%
%                 Setting it true is reserved for
%                 SYNTHETIC unit-path fixtures; such a run is stamped
%                 out.synthetic = true, its guard_validation is forced to 'N/A',
%                 and TASK4_CLASSIFY refuses to classify it. The override does
%                 not weaken the production rule - it marks the run as not a
%                 production run.
%
%   The truth model is the nonlinear relative dynamics; the MPC, the body barrier
%   and the capture barrier all use the CW drift (decision S1).

    if nargin < 2, opt = struct(); end

    % NO SILENT HORIZON DEFAULT. The Task 4 demonstration horizon is explicitly
    % unfrozen, so Tsim must be supplied by the caller on every call. Defaulting
    % it would let an accidental run select a horizon before the horizon-selection
    % rule exists, which the anti-tuning rule forbids.
    assert(isfield(opt,'Tsim') && isscalar(opt.Tsim) && opt.Tsim > 0, ...
        'simulate_task4:Tsim', ...
        ['opt.Tsim must be supplied explicitly and be a positive scalar. The ' ...
         'Task 4 demonstration horizon is NOT frozen, so this function refuses ' ...
         'to choose one for you.']);

    if ~isfield(opt,'x0'),    opt.x0    = [p.scenario.r0; p.scenario.v0]; end
    if ~isfield(opt,'N'),     opt.N     = p.mpc.N;                        end
    if ~isfield(opt,'n_sub'), opt.n_sub = 10;                             end
    if ~isfield(opt,'alpha'), opt.alpha = p.t4.alpha;                     end
    if ~isfield(opt,'allow_inadmissible_ic'), opt.allow_inadmissible_ic = false; end
    % V2 switches (default: frozen behaviour)
    if ~isfield(opt,'v2_preview_online'),    opt.v2_preview_online = false;    end
    if ~isfield(opt,'v2_handoff_tightened'), opt.v2_handoff_tightened = false; end
    % V3 switches (default: V2 behaviour)
    if ~isfield(opt,'v3_qp_exact'),          opt.v3_qp_exact = false;          end
    if ~isfield(opt,'v3_handoff_authority'), opt.v3_handoff_authority = false; end
    if ~isfield(opt,'v3_preview_nsub'),      opt.v3_preview_nsub = 10;         end   % 10 = V2
    assert(~(opt.v3_handoff_authority && ~opt.v2_handoff_tightened), 'simulate_task4_v3:switch', ...
        'v3_handoff_authority refines the V2 rule and requires v2_handoff_tightened = true.');
    if ~isfield(opt,'targetEst')
        opt.targetEst = struct('q', p.target.q0, 'w', p.target.w0, 'I', p.target.I);
    end

    % alpha is a numerical event-detection parameter, NOT a physical tolerance
    % and NOT frozen. It is resolved here so the whole run uses one value and the
    % value is recorded with the results. Only members of the PREDECLARED set are
    % accepted: an unlisted alpha would be a value chosen outside the declared
    % sweep, which the anti-tuning rule forbids.
    assert(isscalar(opt.alpha) && isfinite(opt.alpha) && isreal(opt.alpha), ...
        'simulate_task4:alpha', 'opt.alpha must be a finite real scalar.');
    assert(any(abs(opt.alpha - p.t4.alpha_set) <= 0), 'simulate_task4:alpha', ...
        ['opt.alpha = %g is not a member of the predeclared set [%s]. alpha is a ' ...
         'numerical event-detection parameter and may only take a predeclared ' ...
         'value.'], opt.alpha, num2str(p.t4.alpha_set, '%g '));

    % --- INPUT-INTEGRITY GUARDS. These are not design parameters: they refuse
    % malformed inputs that would otherwise be silently absorbed and produce a
    % run whose reported configuration does not describe what was simulated.
    assert(isscalar(opt.N) && isfinite(opt.N) && opt.N == round(opt.N) && opt.N > 0, ...
        'simulate_task4:N', 'opt.N must be a positive integer; got %g.', opt.N);
    assert(isscalar(opt.n_sub) && isfinite(opt.n_sub) && opt.n_sub == round(opt.n_sub) ...
           && opt.n_sub > 0, 'simulate_task4:n_sub', ...
        'opt.n_sub must be a positive integer; got %g.', opt.n_sub);
    assert(isnumeric(opt.x0) && numel(opt.x0) == 6 && all(isfinite(opt.x0(:))) ...
           && isreal(opt.x0), 'simulate_task4:x0', ...
        'opt.x0 must be a finite real 6-vector; got %d element(s).', numel(opt.x0));

    % Tsim must land exactly on the control grid. Silently rounding a scientific
    % horizon would make out.Tsim and config.Tsim describe a horizon that was not
    % the one simulated.
    nStepsExact = opt.Tsim / p.ctrl.Ts;
    assert(abs(nStepsExact - round(nStepsExact)) <= 1e-9 * max(1, abs(nStepsExact)), ...
        'simulate_task4:grid_Tsim', ...
        ['opt.Tsim = %.12g s is not an integer multiple of Ts = %g s ' ...
         '(Tsim/Ts = %.12g). The horizon is not silently rounded.'], ...
        opt.Tsim, p.ctrl.Ts, nStepsExact);
    opt.Tsim = round(nStepsExact) * p.ctrl.Ts;   % grid-consistent horizon, used and reported

    p.t4.alpha   = opt.alpha;
    p.t4.eps_rho = p.t4.alpha * p.t4.s_cap;
    p.t4.eps_h   = (p.t4.s_cap + p.t4.eps_rho)^2 - p.t4.s_cap^2;

    Ts = p.ctrl.Ts;
    N  = opt.N;
    K  = round(opt.Tsim / Ts);
    t  = (0:K) * Ts;
    pb = p.target.p_cp_body(:);

    % --- frozen Task 3 preview table (MPC layer only) -----------------------
    if isfield(opt, 'tbl') && ~isempty(opt.tbl)
        tbl = opt.tbl;
    else
        tbl = capture_table_build(p, opt.targetEst, opt.Tsim + (N+2)*Ts);
    end
    M = mpc_condensed(p, N);

    % --- measured target attitude/rate (assumption A2) ----------------------
    % Propagated on the INTERSAMPLE grid dt = Ts/n_sub, then subsampled to the
    % control grid. The fine grid is needed because the target tumbles: the
    % intersample h_cap diagnostic must use the capture point at the intersample
    % instant, not the one frozen at t_k.
    dtF = Ts / opt.n_sub;
    pt = p;  pt.sim.dt = dtF;  pt.sim.T_final = opt.Tsim;
    [tF, qF, wF] = target_tumbling_model(pt);
    assert(numel(tF) == K*opt.n_sub + 1, 'simulate_task4:finegrid', ...
        'Fine target history has %d samples, expected K*n_sub+1 = %d.', ...
        numel(tF), K*opt.n_sub + 1);
    ctrlIdx = 1 : opt.n_sub : numel(tF);           % control-grid samples
    tT = tF(ctrlIdx);  qT = qF(:, ctrlIdx);  wT = wF(:, ctrlIdx);
    assert(numel(tT) == K+1, 'simulate_task4:grid', ...
        'Target history has %d samples, expected K+1 = %d.', numel(tT), K+1);

    % --- frozen T4-D4 estimator: records, then causal per-step advance -------
    rec = cl_records(tT, wT, p);
    est = cl_estimator_init(p);

    % --- allocation ----------------------------------------------------------
    X    = zeros(6, K+1);  X(:,1) = opt.x0(:);
    Umpc = zeros(3, K);    Usafe = zeros(3, K);
    hB   = nan(1, K+1);    ps1B  = nan(1, K+1);   ps2B = nan(1, K);
    hC   = nan(1, K+1);    ps1C  = nan(1, K+1);   ps2C = nan(1, K);
    rhoH = nan(1, K+1);    rhoD  = nan(1, K+1);   vrel = nan(1, K+1);
    etaH = nan(1, K);      nuH   = nan(1, K);     lamH = nan(1, K);
    hStarH = nan(1, K);    prevErrH = nan(1, K);  % V2 diagnostics
    qpLevel = zeros(1, K); qpPV = nan(1, K);  qpML = nan(1, K);  qpSlack = zeros(1, K);  % V3
    qpA = nan(2, 3, K);    qpB = nan(2, K);   qpNC = zeros(1, K);                         % V3
    aReqH = nan(1, K);     sigAH = nan(1, K); gateH = false(1, K);                        % V3
    thH  = nan(3, K);      dSafe = nan(1, K+1);
    devH = zeros(1, K);    actH  = false(1, K);
    capEnf   = false(1, K);          % was the capture row in the QP at step k?
    qpInfeas = false(1, K);
    capFeas  = nan(1, K);   bodyFeas = nan(1, K);   jointFeas = nan(1, K);
    capAct   = false(1, K); bodyAct  = false(1, K);
    evH      = repmat({'NONE'}, 1, K);

    handoff_done = false;
    event_log = [];
    event     = 'NO_EVENT';
    aborted = false;  abort_reason = '';
    guard_validation = 'PASS';

    % --- INITIAL HOCBF ADMISSIBILITY GATE ----------------------------------
    % Evaluated and recorded before any control step is taken. A run started
    % outside the applicable admissible set carries no invariance claim, so it
    % must not silently proceed and must never be counted as a safety-validation
    % success or failure. See TASK4_IC_ADMISSIBILITY.
    ic = task4_ic_admissibility(X(:,1), qT(:,1), wT(:,1), est.theta_hat, t(1), p);
    synthetic = false;
    if ~ic.admissible
        if opt.allow_inadmissible_ic
            synthetic        = true;   % SYNTHETIC unit-path fixture, never a result
            guard_validation = 'N/A (synthetic inadmissible-IC override)';
        else
            out = pack_ic_refusal(t, X, qT, wT, ic, p, N, opt);
            return
        end
    end

    interT = []; interHb = []; interHc = []; interR = zeros(3,0);
    odeOpt = odeset('RelTol', 1e-10, 'AbsTol', 1e-12);
    % Clean separation, kept explicit so no downstream slice can silently drop a
    % diagnostic:
    %   kEvaluated - control samples at which the QP was EVALUATED
    %   kApplied   - control samples at which a command was actually APPLIED
    % They differ by exactly one when the run ends on a QP failure.
    %   kDetector  - samples at which the D9 DETECTOR was evaluated (includes the
    %                terminal sample t(K+1) on a completed run)
    kApplied   = K;
    kEvaluated = K;
    kDetector  = 0;
    % Estimator end-state, tracked so it always corresponds to the ACTUAL
    % trajectory end time. cl_estimator_step reads at t_k then advances across
    % [t_k, t_k+Ts); if the run terminates at t_k without applying a command that
    % interval never happens, so the advance must not appear in the reported
    % end-state. The frozen causal estimator law itself is untouched.
    E_end = 0;  theta_end = p.t4.theta_hat0(:);  t_end = t(1);
    qp_failure = struct('occurred', false, 'k', [], 't', [], 'cap_active', [], ...
        'status', [], 'exitflag', [], 'feasible', [], 'feas_margin', [], ...
        'joint_margin', [], 'row_names', {{}});

    for k = 1:K
        xk = X(:,k);

        % --- T4-D4 estimator: values AT t_k, then advance ------------------
        % V2: moved before the MPC layer (numerically neutral, see header).
        [est, ev] = cl_estimator_step(est, t(k), rec, p);

        % --- frozen Task 3 layers: preview + MPC ---------------------------
        if opt.v2_preview_online
            % V2: preview re-anchored on measured (q, w) at t_k with theta_hat(t_k)
            tblL = capture_preview_online_v3(t(k), qT(:,k), wT(:,k), ev.theta_hat, p, N, ...
                                             opt.v3_preview_nsub);               % V3: RK4 substeps
            [Pref, Vref] = capture_reference_preview(0, xk, N, p, tblL);
            prevErrH(k) = norm(tblL.pL(:,1) - tbl.pL(:, round(t(k)/tbl.Ts) + 1));
        else
            [Pref, Vref] = capture_reference_preview(t(k), xk, N, p, tbl);
        end
        u_mpc = mpc_step(xk, Pref, Vref, M, p);
        thH(:,k) = ev.theta_hat;  nuH(k) = ev.nu;  lamH(k) = ev.lambda_min;
        % values AT t_k; they become the reported end-state if the run stops here
        E_end = ev.E;  theta_end = ev.theta_hat;  t_end = t(k);

        % --- barriers -------------------------------------------------------
        [hb, dsf, hdb, Lf2b, Lgb] = safety_function(xk, p, 'cw');
        cb = capture_barrier(xk, qT(:,k), wT(:,k), ev.theta_hat, t(k), p);

        hB(k) = hb;  dSafe(k) = dsf;  ps1B(k) = hdb + p.cbf.k1*hb;
        hC(k) = cb.h;  ps1C(k) = cb.psi1;  etaH(k) = cb.eta;
        rhoH(k) = cb.rho;  rhoD(k) = cb.rho_dot;  vrel(k) = cb.v_rel_cp;
        hStarH(k) = cb.eta * ev.nu / (p.t4.kappa1 * p.t4.kappa2);   % V2 diagnostic

        % --- T4-D9 detector, evaluated on the state BEFORE the command ------
        if opt.v3_handoff_authority
            [evk, dV3] = handoff_detector_v3(cb, ev.nu, xk, handoff_done, p);    % V3
            aReqH(k) = dV3.a_req;  sigAH(k) = dV3.sigma_a;  gateH(k) = dV3.gate;
        elseif opt.v2_handoff_tightened
            evk = handoff_detector_v2(cb, ev.nu, handoff_done, p);    % V2
        else
            evk = handoff_detector(cb.rho, cb.rho_dot, handoff_done, p);
        end
        evH{k} = evk;  kDetector = k;

        if strcmp(evk, 'GUARD_BREACH')
            event_log = log_event(k, t(k), 'GUARD_BREACH', cb, hb, ps1B(k), ev, p);
            event   = 'GUARD_BREACH';
            if synthetic
                verdictTxt = ['the run is SYNTHETIC (inadmissible-IC override), so ' ...
                              'it yields no guard verdict at all'];
            else
                guard_validation = 'FAILED';
                verdictTxt = 'commitment-guard validation FAILED';
            end
            aborted = true;
            abort_reason = sprintf(['GUARD_BREACH at k = %d (t = %.4f s): ' ...
                'rho = %.9f m < s_cap = %.9f m with no prior NORMAL handoff; ' ...
                'run terminated and %s. This is NOT a handoff and counts as no ' ...
                'form of success.'], k, t(k), cb.rho, p.t4.s_cap, verdictTxt);
            % The breach is detected BEFORE the QP call, so no QP was evaluated
            % at this sample. kDetector already records the detector evaluation.
            kApplied   = k - 1;
            kEvaluated = k - 1;
            break
        elseif strcmp(evk, 'NORMAL')
            event_log = log_event(k, t(k), 'NORMAL', cb, hb, ps1B(k), ev, p);
            event   = 'NORMAL';
            handoff_done = true;      % latched, never re-armed within this run
        end

        % --- row set: body always; capture only while not handed off --------
        rows    = struct('A', {-Lgb}, 'b', {Lf2b + (p.cbf.k1+p.cbf.k2)*hdb ...
                                             + p.cbf.k1*p.cbf.k2*hb - p.cbf.delta}, ...
                         'name', {'body'});
        if ~handoff_done
            b_cap = cb.Lf2h + (p.t4.kappa1 + p.t4.kappa2)*cb.hdot ...
                    + p.t4.kappa1*p.t4.kappa2*cb.h - cb.eta*ev.nu;
            rows(2) = struct('A', -cb.Lgh, 'b', b_cap, 'name', 'cap');
            capEnf(k) = true;
        end

        if opt.v3_qp_exact                                                          % V3
            [u_app, finfo] = cbf_qp_two_row_v3(rows, u_mpc, p);
            qpLevel(k) = finfo.level;  qpPV(k) = finfo.kkt.primal_viol;  qpML(k) = finfo.kkt.min_lam;
            qpSlack(k) = finfo.slack;  qpNC(k) = finfo.n_candidates;
            qpA(1:numel(rows), :, k) = finfo.A;  qpB(1:numel(rows), k) = finfo.b;
        else
            [u_app, finfo] = cbf_qp_two_row(rows, u_mpc, p);
        end

        bodyFeas(k)  = finfo.feas_margin(1);
        bodyAct(k)   = finfo.row_active(1);
        jointFeas(k) = finfo.joint_margin;
        if capEnf(k)
            capFeas(k) = finfo.feas_margin(2);
            capAct(k)  = finfo.row_active(2);
        end

        if ~finfo.feasible && opt.v3_qp_exact
            % V3: the HARD problem was not solved. The fallback command (level 1 or 2, in
            % qpLevel) is applied and the run continues; counted separately, never as level 0.
            qpInfeas(k) = true;
        elseif ~finfo.feasible
            qpInfeas(k) = true;
            % RUN-LEVEL QP-FAILURE RECORD. The per-step arrays below are sliced
            % to the steps at which a command was actually APPLIED, and no
            % command was applied at this step - so the failing step is not in
            % them, by design. Without this record the F3 trigger, "any QP
            % infeasibility while h_cap is active", could never fire. This record
            % is the authoritative F3 source; it does not pretend a command was
            % applied here.
            qp_failure = struct( ...
                'occurred',      true, ...
                'k',             k, ...
                't',             t(k), ...
                'cap_active',    capEnf(k), ...
                'status',        finfo.status, ...
                'exitflag',      finfo.exitflag, ...
                'feasible',      false, ...
                'feas_margin',   finfo.feas_margin, ...   % per-row individual
                'joint_margin',  finfo.joint_margin, ...
                'row_names',     {finfo.names});
            aborted = true;
            abort_reason = sprintf(['Two-row QP infeasible at k = %d (t = %.4f s); ' ...
                'capture row %s enforced. No command was applied at this step; ' ...
                'the trajectory ends here and the failure is recorded in ' ...
                'out.qp_failure.'], k, t(k), ternary(capEnf(k), 'WAS', 'was NOT'));
            kApplied  = k - 1;
            kEvaluated = k;
            break
        end

        Umpc(:,k) = u_mpc;  Usafe(:,k) = u_app;
        devH(k) = finfo.dev_inf;  actH(k) = finfo.active;
        ps2B(k) = (Lf2b + Lgb*u_app) + (p.cbf.k1+p.cbf.k2)*hdb + p.cbf.k1*p.cbf.k2*hb;
        ps2C(k) = (cb.Lf2h + cb.Lgh*u_app) + (p.t4.kappa1+p.t4.kappa2)*cb.hdot ...
                  + p.t4.kappa1*p.t4.kappa2*cb.h;

        % --- plant ----------------------------------------------------------
        tsub = linspace(t(k), t(k+1), opt.n_sub + 1);
        [~, Xs] = ode45(@(tt, xx) rel_translational_dynamics(xx, u_app, p, 'nonlinear'), ...
                        tsub, xk, odeOpt);
        X(:,k+1) = Xs(end,:).';

        % Intersample record. h_body follows the frozen Task 3 diagnostic. The
        % h_cap value is DIAGNOSTIC ONLY: the frozen classifier is defined on
        % sampled values (freeze record Sec. 8.6) and no intersample invariance
        % is claimed anywhere. It is recorded because freeze-record Sec. 3.3
        % asks for intersample behaviour to be measured rather than assumed.
        %
        % The capture point MOVES within the control interval, so h_cap at the
        % intersample instant must use p_cp(tsub(j)), NOT p_cp(t_k). Holding the
        % control-sample capture point fixed across the interval would understate
        % or overstate the diagnostic by the target's own motion.
        for j = 2:opt.n_sub
            xj  = Xs(j,:).';
            jF  = (k-1)*opt.n_sub + j;                 % fine-grid index of tsub(j)
            [~, R_LIj, ~] = lvlh_frame(tsub(j), p);
            p_cp_j = R_LIj * quat_to_rotm(qF(:,jF)) * pb;
            interT(end+1)  = tsub(j);                          %#ok<AGROW>
            interHb(end+1) = safety_function(xj, p, 'cw');     %#ok<AGROW>
            interHc(end+1) = norm(xj(1:3) - p_cp_j)^2 - p.t4.s_cap^2;   %#ok<AGROW>
            interR(:,end+1) = xj(1:3);                         %#ok<AGROW>
        end

        % The command was applied and the interval [t_k, t_k+Ts) was executed, so
        % the estimator advance across it is now real and may be reported.
        E_end = est.E;  theta_end = est.theta_hat;  t_end = t(k+1);
    end

    % --- terminal sample bookkeeping (only if the run completed) ------------
    if ~aborted
        [hB(K+1), dSafe(K+1), hdE] = safety_function(X(:,K+1), p, 'cw');
        ps1B(K+1) = hdE + p.cbf.k1*hB(K+1);
        cbE = capture_barrier(X(:,K+1), qT(:,K+1), wT(:,K+1), est.theta_hat, t(K+1), p);
        hC(K+1) = cbE.h;  ps1C(K+1) = cbE.psi1;
        rhoH(K+1) = cbE.rho;  rhoD(K+1) = cbE.rho_dot;  vrel(K+1) = cbE.v_rel_cp;
        kApplied = K;  kEvaluated = K;

        % --- D9 AT THE TERMINAL SAMPLE -------------------------------------
        % The frozen D9 outcome is defined over SAMPLED trigger satisfaction, and
        % t(K+1) is a sampled state. Evaluating the detector only inside the
        % k = 1..K loop would silently exclude it, so a run whose final sample
        % satisfies the NORMAL trigger would be misreported as NO_EVENT.
        %
        % The estimator is NOT advanced to build these diagnostics: theta_hat and
        % E are read from the state the loop already left at t(K+1), so nu here is
        % nu_sp(t(K+1)) by the canonical causal definition.
        if opt.v3_handoff_authority                                     % V3
            evT = handoff_detector_v3(cbE, p.t4.nu0 * exp(-p.t4.gamma * est.E), X(:,K+1), handoff_done, p);
        elseif opt.v2_handoff_tightened                                 % V2
            evT = handoff_detector_v2(cbE, p.t4.nu0 * exp(-p.t4.gamma * est.E), handoff_done, p);
        else
            evT = handoff_detector(cbE.rho, cbE.rho_dot, handoff_done, p);
        end
        kDetector = K + 1;
        if ~strcmp(evT, 'NONE')
            evTerm = struct('theta_hat', est.theta_hat, ...
                            'nu', p.t4.nu0 * exp(-p.t4.gamma * est.E));
            [hbT, ~, hdbT] = safety_function(X(:,K+1), p, 'cw');
            event_log = log_event(K+1, t(K+1), evT, cbE, hbT, hdbT + p.cbf.k1*hbT, evTerm, p);
            event     = evT;
            if strcmp(evT, 'NORMAL')
                % No control step follows the terminal sample, so there is no row
                % set to switch; the latch is set for reporting consistency only.
                handoff_done = true;
            else
                guard_validation = 'FAILED';   % terminal GUARD_BREACH
            end
        end
    end

    % --- pack ----------------------------------------------------------------
    ns  = min(kApplied+1, K+1);
    idx = 1:kApplied;   idxS = 1:ns;

    out.t = t(idxS);              out.X = X(:, idxS);
    out.qT = qT(:, idxS);         out.wT = wT(:, idxS);
    out.Umpc = Umpc(:, idx);      out.Usafe = Usafe(:, idx);
    out.h_body = hB(idxS);        out.psi1_body = ps1B(idxS);  out.psi2_body = ps2B(idx);
    out.h_cap  = hC(idxS);        out.psi1_cap  = ps1C(idxS);  out.psi2_cap  = ps2C(idx);
    out.d_safe = dSafe(idxS);
    out.rho = rhoH(idxS);         out.rho_dot = rhoD(idxS);    out.v_rel_cp = vrel(idxS);
    out.eta = etaH(idx);          out.nu = nuH(idx);           out.lambda_min = lamH(idx);
    out.v2 = struct('preview_online', opt.v2_preview_online, ...
                    'handoff_tightened', opt.v2_handoff_tightened, ...
                    'h_star', hStarH(idx), 'preview_anchor_vs_table_m', prevErrH(idx));  % V2
    out.v3 = struct('qp_exact', opt.v3_qp_exact, 'handoff_authority', opt.v3_handoff_authority, ...
                    'qp_level', qpLevel(idx), 'qp_primal_viol', qpPV(idx), 'qp_min_lam', qpML(idx), ...
                    'qp_slack', qpSlack(idx), 'qp_A', qpA(:, :, idx), 'qp_b', qpB(:, idx), ...
                    'qp_n_candidates', qpNC(idx), 'a_req', aReqH(idx), 'sigma_a', sigAH(idx), ...
                    'gate', gateH(idx), 'gamma_c', 1 - p.capture.beta, ...
                    'preview_nsub', opt.v3_preview_nsub);                                  % V3
    out.theta_hat = thH(:, idx);  out.theta_true = p.t4.theta_true;
    out.dev_inf = devH(idx);      out.active = actH(idx);
    out.cap_enforced = capEnf(idx);   out.qp_infeasible = qpInfeas(idx);
    out.feas_body = bodyFeas(idx);    out.feas_cap = capFeas(idx);
    out.feas_joint = jointFeas(idx);
    out.row_active_body = bodyAct(idx);  out.row_active_cap = capAct(idx);
    out.events = evH(idx);

    % A SYNTHETIC run can never produce a guard verdict, whatever happened inside
    % it. Forcing this here means no code path can leak a PASS or FAILED out of
    % an overridden inadmissible initial condition.
    if synthetic
        guard_validation = 'N/A (synthetic inadmissible-IC override)';
    end

    out.ic          = ic;           % initial-admissibility record, always present
    out.synthetic   = synthetic;    % true only for an overridden inadmissible IC
    out.eligibility = 'ELIGIBLE';   % pre-run status; see PACK_IC_REFUSAL
    out.d9_evaluated = true;        % the detector ran at every control step
    out.event       = event;        % D9 outcome: NORMAL | GUARD_BREACH | NO_EVENT
    out.event_log = event_log;      % firing-sample diagnostics for either event, or []
    % out.handoff is populated ONLY by a NORMAL event. A GUARD_BREACH must never
    % latch a handoff, so it must never appear here either.
    if strcmp(event, 'NORMAL'), out.handoff = event_log; else, out.handoff = []; end
    out.handoff_done = handoff_done;
    out.guard_validation = guard_validation;
    out.aborted = aborted;          out.abort_reason = abort_reason;
    out.alpha = p.t4.alpha;         out.eps_rho = p.t4.eps_rho;
    out.eps_h = p.t4.eps_h;         out.s_cap = p.t4.s_cap;
    out.alpha_status = p.t4.alpha_status;
    out.kappa = [p.t4.kappa1, p.t4.kappa2];
    % Estimator end-state at the ACTUAL trajectory end time t_end, never through
    % an interval that was not executed.
    out.estimator = struct('records', rec.n, 'resid', rec.resid, ...
                           't_end', t_end, 'E_end', E_end, ...
                           'theta_hat_end', theta_end, ...
                           'nu_end', p.t4.nu0 * exp(-p.t4.gamma * E_end), ...
                           'Tw', p.t4.Tw, 'M', p.t4.M, 'gamma', p.t4.gamma);
    out.qp_failure  = qp_failure;   % authoritative F3 source; see the break above
    out.K_applied   = kApplied;     % control commands actually APPLIED
    out.K_evaluated = kEvaluated;   % QPs actually EVALUATED
    out.K_detector  = kDetector;    % samples at which the D9 detector was evaluated
    out.t_end       = t_end;        % actual trajectory end time
    out.N = N;   out.K = kApplied;   out.Tsim = opt.Tsim;
    out.config = run_config(p, opt, N);
    % Intersample positions are stored so the h_cap diagnostic can be checked
    % against an independently reconstructed capture-point trajectory.
    out.inter = struct('t', interT, 'h_body', interHb, 'h_cap_diag', interHc, ...
                       'r', interR);
end

% ===== local functions =====================================================
function c = run_config(p, opt, N)
% SANITIZED NON-ALPHA RUN SPECIFICATION. TASK4_CLASSIFY compares this across the
% three sweep runs to enforce the frozen "everything else identical" replay rule.
%
% WHY THE WHOLE p AND opt, NOT A CURATED LIST. A hand-maintained list of "the
% fields that matter" is fragile: it silently omits anything added later, and it
% already omitted the TRUTH target propagation (p.target, p.orbit) and any
% caller-supplied preview table, both of which determine the trajectory. Storing
% the complete inputs with only the alpha-derived fields removed makes omission
% impossible by construction. p is a pure numeric/char struct, so an exact
% comparison is well defined.
%
% Removed: alpha and the two quantities derived from it. Those are the only
% things the sweep is allowed to vary.
    c.p = p;
    c.p.t4 = rmfield(c.p.t4, {'alpha', 'eps_rho', 'eps_h'});

    c.opt = opt;
    if isfield(c.opt, 'alpha'), c.opt = rmfield(c.opt, 'alpha'); end

    % A caller-supplied preview table is a trajectory-generating input, so its
    % CONTENT is part of the replay identity. When no table is supplied the table
    % is derived deterministically from (p, targetEst, Tsim, N), all of which are
    % already compared above, so only the custom case needs to be carried.
    c.custom_tbl = isfield(opt, 'tbl') && ~isempty(opt.tbl);
    if ~c.custom_tbl && isfield(c.opt, 'tbl')
        c.opt = rmfield(c.opt, 'tbl');
    end

    c.N  = N;
    c.Ts = p.ctrl.Ts;
end

function out = pack_ic_refusal(t, X, qT, wT, ic, p, N, opt)
% A production run refused at the entry gate. It produces NO trajectory, NO
% event and NO guard verdict: guard_validation is 'N/A', neither PASS nor
% FAILED, so the run can never be counted in either direction.
    out.t  = t(1);             out.X  = X(:,1);
    out.qT = qT(:,1);          out.wT = wT(:,1);
    out.Umpc = zeros(3,0);     out.Usafe = zeros(3,0);
    out.h_body = ic.h_body;    out.psi1_body = ic.psi1_body;  out.psi2_body = [];
    out.h_cap  = ic.h_cap;     out.psi1_cap  = ic.psi1_cap;   out.psi2_cap  = [];
    out.d_safe = NaN;
    out.rho = ic.rho;          out.rho_dot = ic.rho_dot;      out.v_rel_cp = NaN;
    out.eta = [];              out.nu = [];                   out.lambda_min = [];
    out.theta_hat = zeros(3,0);   out.theta_true = p.t4.theta_true;
    out.dev_inf = [];          out.active = false(1,0);
    out.cap_enforced = false(1,0);   out.qp_infeasible = false(1,0);
    out.feas_body = [];        out.feas_cap = [];             out.feas_joint = [];
    out.row_active_body = false(1,0);   out.row_active_cap = false(1,0);
    out.events = {};
    out.ic = ic;               out.synthetic = false;
    % PRE-RUN VALIDATION-ELIGIBILITY status. This is NOT a D9 outcome: D9 stays
    % frozen with exactly NORMAL, GUARD_BREACH and NO_EVENT, and the detector
    % never ran here, so the run has none of them.
    out.eligibility   = 'INELIGIBLE_IC';
    out.d9_evaluated  = false;
    out.event         = 'NOT_EVALUATED';   % absence of a D9 outcome, not an outcome
    out.event_log = [];        out.handoff = [];              out.handoff_done = false;
    out.guard_validation = 'N/A';
    out.aborted = true;
    out.abort_reason = sprintf(['INELIGIBLE_IC: the initial condition lies ' ...
        'outside the applicable HOCBF admissible set, so no invariance claim ' ...
        'applies and the run is refused before any control step. D9 was NOT ' ...
        'EVALUATED. This is a validation-eligibility status, not a D9 outcome, ' ...
        'and it is neither a guard failure nor a guard success. Reasons: %s'], ...
        strjoin(ic.reasons, ' | '));
    out.alpha = p.t4.alpha;    out.eps_rho = p.t4.eps_rho;
    out.eps_h = p.t4.eps_h;    out.s_cap = p.t4.s_cap;
    out.alpha_status = p.t4.alpha_status;
    out.kappa = [p.t4.kappa1, p.t4.kappa2];
    out.estimator = struct('records', 0, 'resid', NaN, 't_end', t(1), 'E_end', 0, ...
        'theta_hat_end', p.t4.theta_hat0, 'nu_end', p.t4.nu0, ...
        'Tw', p.t4.Tw, 'M', p.t4.M, 'gamma', p.t4.gamma);
    out.qp_failure  = struct('occurred', false, 'k', [], 't', [], ...
        'cap_active', [], 'status', [], 'exitflag', [], 'feasible', [], ...
        'feas_margin', [], 'joint_margin', [], 'row_names', {{}});
    out.K_applied = 0;   out.K_evaluated = 0;   out.K_detector = 0;
    out.t_end = t(1);
    out.N = N;   out.K = 0;   out.Tsim = opt.Tsim;
    out.config = run_config(p, opt, N);
    out.inter = struct('t', [], 'h_body', [], 'h_cap_diag', [], 'r', zeros(3,0));
end

function s = log_event(k, tk, kind, cb, hb, ps1b, ev, p)
% D9 firing-sample diagnostics, exactly the set frozen in Sec. 8.2.
    s.t            = tk;
    s.k            = k;
    s.event        = kind;
    s.rho          = cb.rho;
    s.rho_dot      = cb.rho_dot;
    s.v_rel_cp     = cb.v_rel_cp;      % ||v - v_cp||
    s.nu           = ev.nu;
    s.h_body       = hb;
    s.psi1_body    = ps1b;
    s.h_cap        = cb.h;
    s.psi1_cap     = cb.psi1;
    s.alpha        = p.t4.alpha;
    s.eps_rho      = p.t4.eps_rho;
    % supporting context, not part of the frozen minimum set
    s.theta_hat    = ev.theta_hat;
    s.eta          = cb.eta;
    s.s_cap        = p.t4.s_cap;
end

function s = ternary(c, a, b)
    if c, s = a; else, s = b; end
end
