function mc_shard_plan_check(plan, ctx, condition)
% MC_SHARD_PLAN_CHECK  A shard plan is a disjoint, complete partition of the trials.
%   mc_shard_plan_check(plan, ctx, condition) refuses ('mc:plan:*') unless:
%   the schema is task4_mc_shard_plan_v1; the plan is for this condition and
%   carries this campaign's binding and intended trial set; there are 1 to 3
%   shards named S1..Sn; every shard is a non-empty, strictly increasing
%   integer vector; shards are pairwise DISJOINT; their union is EXACTLY the
%   intended trial set.

    need = {'schema', 'condition', 'binding', 'trial_ids', 'shard_ids', 'shards', ...
            'operator', 'created_utc', 'process'};
    assert(isstruct(plan) && isscalar(plan) && all(isfield(plan, need)) ...
        && strcmp(plan.schema, 'task4_mc_shard_plan_v1'), 'mc:plan:schema', ...
        'Not a task4_mc_shard_plan_v1 plan.');
    assert(strcmp(plan.condition, condition), 'mc:plan:condition', ...
        'The plan is for condition %s, not %s.', plan.condition, condition);
    assert(isequal(plan.binding, ctx.binding) && isequal(plan.trial_ids, ctx.trial_ids), ...
        'mc:plan:binding', 'The plan belongs to a different campaign or trial set.');
    n = numel(plan.shards);
    assert(iscell(plan.shards) && any(n == 1:3) && iscell(plan.shard_ids) ...
        && isequal(plan.shard_ids, arrayfun(@(k) sprintf('S%d', k), 1:n, 'UniformOutput', false)), ...
        'mc:plan:shards', 'A plan has 1 to 3 shards named S1..Sn.');
    all_ids = [];
    for k = 1:n
        s = plan.shards{k};
        assert(isnumeric(s) && isrow(s) && ~isempty(s) && all(s == round(s)) ...
            && all(diff(s) > 0), 'mc:plan:shard_shape', ...
            'Shard %s is not a non-empty strictly increasing integer row.', plan.shard_ids{k});
        all_ids = [all_ids, s]; %#ok<AGROW>
    end
    assert(numel(unique(all_ids)) == numel(all_ids), 'mc:plan:overlap', ...
        'REFUSED: a trial appears in more than one shard.');
    assert(isequal(sort(all_ids), ctx.trial_ids), 'mc:plan:incomplete', ...
        'REFUSED: the shards do not cover exactly the intended trial set.');
end
