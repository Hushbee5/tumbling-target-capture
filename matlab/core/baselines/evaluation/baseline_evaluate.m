function [summary, identities] = baseline_evaluate(opt)
% BASELINE_EVALUATE  The one-shot deterministic baseline evaluation (Sec. 11).
%   [summary, identities] = baseline_evaluate(opt) runs the NOMINAL MPC and the
%   APF baseline once each, at the frozen evaluation scenario, behind the Sec. 11
%   preflight gate, and writes the three predeclared artifacts.
%
%       Scenario      x0 = [0; -10; 0; 0; 0; 0] , frozen target q0, w0, I
%       Horizon       T = 800 s
%       Methods run   NOMINAL MPC and APF (Candidate A) only
%       Destinations  results/task4/baselines/   -- FROZEN, not redirectable
%
%   THE PROPOSED METHOD IS NOT RERUN. Its immutable 800 s artifacts are compared
%   against BY HASH; the preflight verifies all four and names the headline
%   pre-result nominal alpha = 1e-3 reference. The alpha = 1e-2 and 1e-4
%   artifacts remain SENSITIVITY results and may not be substituted after
%   baseline results are known.
%
%   REQUIRED OPTIONS - none of these has a default:
%       expected_aggregate        the ONE frozen baseline-support aggregate
%                                 SHA-256 from Source-Freeze Record B
%       gain_record               path to the hash-frozen tuning record .mat
%       gain_record_sha256        its frozen SHA-256
%       verification_gate_sha256  the frozen V1-V11 gate SHA-256 that the tuning
%                                 record must have been authorised by
%
%   THE GAIN SET COMES FROM THE HASH-FROZEN TUNING RECORD, never from an
%   argument typed here, and the record is checked before it is trusted: its
%   hash, its outcome, its protocol binding, its source binding, its V1-V11 gate
%   binding, its scenario count and horizon, and the internal consistency of the
%   winner it names - id, eligibility, levels, ordering vector, round, theta,
%   and that the winner IS the stored terminal incumbent decision (the last
%   COMPLETE refinement round's incumbent_after, or the frozen post-coarse
%   incumbent). The executed theta is then built from the MATCHED CANDIDATE, not
%   from the winner struct's duplicate copy. NOTHING IS RECOMPUTED, RERANKED OR
%   RETUNED - this is stored-state replay and integrity validation only.
%
%   NO-RETUNING RULE (Sec. 13). Once this function has run, no gain, lattice
%   level, bracket, metric definition, taxonomy category, stencil, tolerance,
%   selection horizon or reporting layer may be changed. An unfavourable
%   baseline result is data. A favourable one is data. Neither licenses a change.
%
%   THIS IS THE ONLY PLACE allow_eval_x0 IS EVER SET. Everywhere else the
%   evaluation initial condition is FORBIDDEN and is refused by both
%   BASELINE_SCENARIOS and SIMULATE_BASELINE.
%
%   ORDER OF FINAL WRITES, HASHES AND THE POSTFLIGHT (protocol Sec. 15.4):
%       nominal final write -> immediate identity (SHA-256, bytes, timestamp)
%       APF     final write -> immediate identity
%       summary FINAL write -> immediate identity     (written EXACTLY ONCE)
%       THEN the final post-run integrity recheck of every Section-2 identity
%   The authoritative final postflight therefore runs AFTER all three artifacts
%   exist and have been hashed, and it lives ONLY in the returned `identities`
%   object as identities.post_run_integrity - writing it into the summary would
%   require rewriting the summary and would invalidate the hash just taken over
%   it. An earlier check is retained as an ADDITIONAL diagnostic under the
%   distinct name summary.pre_summary_integrity; it is NOT the final postflight.
%   The summary's OWN identity exists only in the returned object, which avoids
%   a self-hash cycle without inventing an extra scientific result file.
%
%   EXECUTION-INTEGRITY TAXONOMY IS PRESERVED, AND IT GATES THE METRIC LAYER.
%   A run is scientifically COMPLETE iff
%       run.completed && run.numerically_eligible
%   ~numerical_failure alone is NOT sufficient: numerical eligibility also
%   requires every result-relevant history to be finite. BASELINE_METRICS is
%   called ONLY for a run that satisfies that condition. A failed run is written
%   to its frozen destination as EXECUTION-FAILURE EVIDENCE - variable
%   `execution_failure`, no artifact/metrics/schema_report variable, no V11
%   schema PASS claimed - and the invocation continues to the other baseline
%   with NO retry. A caught ode45 failure may leave finite partial histories;
%   they are diagnostic evidence only, never the frozen 800 s scientific
%   metrics. artifact_status is COMPLETE only when BOTH baselines satisfy the
%   condition above; otherwise EXECUTION_FAILURE_NUMERICAL. That is
%   execution-status metadata and is never a scientific outcome.

    % ---- required options ---------------------------------------------------
    assert(nargin >= 1 && isstruct(opt), 'baseline_evaluate:opt', ...
        'An options struct is required.');
    req = {'expected_aggregate', 'gain_record', 'gain_record_sha256', ...
           'verification_gate_sha256'};
    for i = 1:numel(req)
        assert(isfield(opt, req{i}) && ~isempty(opt.(req{i})), ...
            'baseline_evaluate:required_option', ...
            ['opt.%s is REQUIRED and has no default. The frozen aggregate, the ' ...
             'frozen tuning record and the frozen V1-V11 gate are external ' ...
             'identities; this harness verifies them, it does not invent them.'], ...
            req{i});
    end
    expAgg = lower(char(opt.expected_aggregate));

    thisDir  = fileparts(mfilename('fullpath'));
    repoRoot = fileparts(fileparts(fileparts(thisDir)));
    w = what(repoRoot);  if ~isempty(w), repoRoot = w(1).path; end

    % ---- the FROZEN destination directory ----------------------------------
    % Sec. 11 names the three destinations exactly. Redirecting them would let a
    % second "one-shot" evaluation be written somewhere the preflight's
    % destination-absence check never looks, which is precisely the discipline
    % that check exists to enforce.
    outDir = fullfile(repoRoot, 'results', 'task4', 'baselines');
    if isfield(opt, 'out_dir') && ~isempty(opt.out_dir)
        assert(strcmpi(canonical(opt.out_dir), canonical(outDir)), ...
            'baseline_evaluate:out_dir', ...
            ['The deterministic output directory is FROZEN at\n    %s\nand may ' ...
             'not be redirected to\n    %s'], outDir, opt.out_dir);
    end

    p = baseline_config();

    dest = struct( ...
        'nominal_mpc', fullfile(outDir, 'baseline_nominal_mpc_800s.mat'), ...
        'apf',         fullfile(outDir, 'baseline_apf_800s.mat'), ...
        'summary',     fullfile(outDir, 'baseline_800s_summary.mat'));
    destList = {dest.nominal_mpc, dest.apf, dest.summary};

    % ---- PREFLIGHT: nothing is created before this passes ------------------
    preOpt = struct('repo_root', repoRoot, 'destinations', {destList}, ...
                    'expected_aggregate', expAgg);
    pre = baseline_preflight(p, preOpt);

    % ---- the frozen tuning record, verified before it is trusted -----------
    [theta, gainProv] = load_frozen_gains(opt, p, pre, expAgg);
    gains = apf_gains(theta, p);
    r1    = apf_r1_margin(gains, p);

    % ---- the frozen evaluation scenario ------------------------------------
    x0 = p.bl.eval_x0;
    assert(isequal(x0, [0; -10; 0; 0; 0; 0]), 'baseline_evaluate:x0', ...
        'The evaluation initial condition is not the frozen [0; -10; 0; 0; 0; 0].');
    targetIC = struct('q', p.target.q0, 'w', p.target.w0, 'I', p.target.I);
    tabs = baseline_capture_tables(p, targetIC, targetIC, p.bl.T_eval);

    % ---- the V2c preview/truth audit, attached to EVERY artifact (V11b) ----
    % Computed from the already-built full deterministic target tables by the
    % same shared function the V1-V11 gate uses, so the artifact carries the
    % real audit rather than a marker that one was performed elsewhere.
    v2c = baseline_preview_truth_audit(tabs, 1e-6, 1e-6);

    head  = pre.git_head;
    stamp = datestr(now, 'yyyy-mm-dd HH:MM:SS');            %#ok<TNOW1,DATST>
    man   = baseline_manifest();

    if ~exist(outDir, 'dir'), mkdir(outDir); end

    % ---- the two runs, in a fixed order, with no retry ---------------------
    methods = {'nominal_mpc', 'apf'};
    arts = struct();  reps = struct();  runs = struct();
    statuses = struct();
    identities = struct();
    anyFailure = false;

    for i = 1:numel(methods)
        mth = methods{i};
        runOpt = struct('method', mth, 'x0', x0, 'Tsim', p.bl.T_eval, ...
            'truthIC', targetIC, 'previewIC', targetIC, 'tables', tabs, ...
            'allow_eval_x0', true);          % the ONLY place this is ever set
        if strcmp(mth, 'apf')
            runOpt.gains = gains;
            runOpt.r1    = r1;
        end

        t0  = tic;
        run = simulate_baseline(p, runOpt);
        rt  = toc(t0);
        runs.(mth) = run;

        % A deterministic run is scientifically COMPLETE only if it completed
        % the horizon AND is numerically eligible. ~numerical_failure is NOT
        % sufficient: numerically_eligible additionally requires every
        % result-relevant history to be finite, and it is the verdict
        % SIMULATE_BASELINE publishes for exactly this decision.
        runComplete = run.completed && run.numerically_eligible;
        anyFailure  = anyFailure || ~runComplete;

        if runComplete
            aStatus = 'COMPLETE';
        else
            aStatus = 'EXECUTION_FAILURE_NUMERICAL';
        end

        prov = struct( ...
            'run_identity', struct('method', mth, 'config', run.config, ...
                'gain_record', opt.gain_record, ...
                'gain_record_sha256', gainProv.gain_record_sha256, ...
                'theta', theta), ...
            'meta', struct('runtime_s', rt, 'preflight', pre, ...
                'v2c', v2c, ...
                'gain_provenance', gainProv, ...
                'headline_reference', pre.headline_reference, ...
                'headline_note', pre.headline_note, ...
                'harness', 'baseline_evaluate'), ...
            'git_head', head, ...
            'stamp',    stamp, ...
            'protocol_sha',           p.bl.protocol_sha256, ...
            'baseline_aggregate_sha', expAgg, ...
            'artifact_status',        aStatus, ...
            'note', ['Deterministic baseline evaluation. Body safety is a GRID ' ...
                'result over the inspected union, never a continuous-time ' ...
                'guarantee. Proximity is a method-neutral milestone and is ' ...
                'NEVER described as capture or grasp. Delta-v is a cumulative ' ...
                'acceleration impulse under an identical actuator model, NEVER ' ...
                'fuel or propellant.']);

        f = dest.(mth);
        assert(exist(f, 'file') ~= 2, 'baseline_evaluate:exists_late', ...
            'ABORT: destination appeared during the evaluation: %s', f);

        if runComplete
            % ---- SCIENTIFIC PATH, unchanged --------------------------------
            % BASELINE_METRICS IS CALLED ONLY HERE. Body safety, proximity,
            % Delta-v, efficiency and the T-inputs are scientific quantities,
            % and they are computed only for a run that completed the horizon
            % AND is numerically eligible.
            m   = baseline_metrics(run, p);
            art = baseline_artifact(run, m, prov);
            rep = baseline_schema(art, mth, m);

            schema_report = rep;
            artifact = art;
            metrics  = m;
            save(f, 'artifact', 'metrics', 'schema_report', '-v7.3');

            arts.(mth) = art;
            reps.(mth) = rep;
            fprintf([' %s: K = %d, proximity = %d, no_violation = %d, ' ...
                'DeltaV_full = %.6g m/s, status %s\n'], mth, art.K, ...
                art.proximity_achieved, art.no_observed_body_violation, ...
                art.DeltaV_full, aStatus);
        else
            % ---- EXECUTION-FAILURE EVIDENCE PATH ---------------------------
            % BASELINE_METRICS IS DELIBERATELY NOT CALLED. A run that did not
            % complete the horizon, or that carries a non-finite
            % result-relevant history, HAS NO frozen 800 s scientific metrics.
            % Computing them anyway would manufacture body-safety, proximity,
            % Delta-v and T-input numbers out of partial or invalid data and
            % file them under the same names the healthy path uses.
            %
            % The destination is still written, so the failure is AUDITABLE,
            % but it holds EVIDENCE rather than an artifact: the saved variable
            % is execution_failure, the file contains NO variable named
            % artifact, metrics or schema_report, and nothing here claims a V11
            % schema PASS. The frozen one-shot invocation then continues to the
            % other baseline. THERE IS NO RETRY.
            %
            % A caught ode45 failure may leave finite partial histories. Those
            % are diagnostic failure evidence only; they are not the frozen
            % 800 s scientific metrics and must never be reported as such.
            execution_failure = struct( ...
                'status',               aStatus, ...
                'method',               mth, ...
                'is_scientific_result', false, ...
                'metrics_available',    false, ...
                'metrics',              [], ...
                'schema_applicable',    false, ...
                'schema_report',        [], ...
                'completed',            run.completed, ...
                'numerically_eligible', run.numerically_eligible, ...
                'numerical_failure',    run.numerical_failure, ...
                'failure_k',            run.failure_k, ...
                'failure_reason',       run.failure_reason, ...
                'nonfinite_fields',     {run.nonfinite_fields}, ...
                'K',                    run.K, ...
                'K_expected',           run.K_expected, ...
                'partial_run',          run, ...
                'provenance',           prov, ...
                'note', ['EXECUTION-FAILURE EVIDENCE, NOT A SCIENTIFIC ' ...
                    'RESULT. BASELINE_METRICS was NOT called for this run, so ' ...
                    'no body-safety, proximity, Delta-v, efficiency or T-input ' ...
                    'value exists for it and none was fabricated. The V11 ' ...
                    'scientific logging schema does NOT apply and no schema ' ...
                    'PASS is claimed. partial_run holds the raw, possibly ' ...
                    'partial histories for diagnosis only: a caught ode45 ' ...
                    'failure can leave finite partial histories, and those are ' ...
                    'still not the frozen 800 s scientific metrics. The frozen ' ...
                    'one-shot invocation continued to the other baseline; no ' ...
                    'retry was performed.']);
            artifact_status = aStatus;
            save(f, 'execution_failure', 'artifact_status', '-v7.3');

            reps.(mth) = struct('applicable', false, 'pass', false, ...
                'note', ['No V11 schema evaluation: the run is ' ...
                         'EXECUTION_FAILURE_NUMERICAL and produced no ' ...
                         'scientific artifact.']);
            fprintf(2, [' %s: %s -- K = %d of %d, numerically_eligible = %d. ' ...
                'NO scientific metrics were computed for this run.\n'], ...
                mth, aStatus, run.K, run.K_expected, run.numerically_eligible);
            if ~isempty(run.failure_reason)
                fprintf(2, '      reason: %s\n', run.failure_reason);
            end
        end

        % FINAL WRITE for this destination -> identity taken immediately.
        identities.(mth) = file_identity(f);
        statuses.(mth)   = aStatus;
        fprintf('   -> %s\n      sha %s  %d bytes  [%s]\n', f, ...
            identities.(mth).sha256, identities.(mth).bytes, aStatus);
    end

    % ---- PRE-SUMMARY INTEGRITY DIAGNOSTIC (NOT the final postflight) -------
    % An additional diagnostic taken after the two run artifacts exist and
    % before the summary is written, so its result can be carried INSIDE the
    % summary. It is NOT the authoritative post-run integrity check: protocol
    % Sec. 15.4 places that AFTER the artifacts are hashed, and it runs at the
    % end of this function into the returned identities object.
    postOpt = preOpt;
    postOpt.require_destinations_absent = false;
    preSummaryIntegrity = baseline_preflight(p, postOpt);

    if anyFailure
        artifact_status = 'EXECUTION_FAILURE_NUMERICAL';
    else
        artifact_status = 'COMPLETE';
    end

    summary = struct( ...
        'scenario_x0',   x0, ...
        'Tsim',          p.bl.T_eval, ...
        'methods',       {methods}, ...
        'theta',         theta, ...
        'gains',         struct('k_a', gains.k_a, 'k_d', gains.k_d, 'k_r', gains.k_r), ...
        'r1_margin',     r1.r1_margin, ...
        'gain_provenance', gainProv, ...
        'preflight',     pre, ...
        'pre_summary_integrity', preSummaryIntegrity, ...
        'v2c',           v2c, ...
        'schema_reports', reps, ...
        'per_method_status', statuses, ...
        'artifact_identities', identities, ...
        'proposed_method_rerun', false, ...
        'headline_reference',    pre.headline_reference, ...
        'headline_note',         pre.headline_note, ...
        'baseline_aggregate_sha', expAgg, ...
        'protocol_sha',  p.bl.protocol_sha256, ...
        'baseline_file_count', man.count, ...
        'git_head',      head, ...
        'stamp',         stamp, ...
        'artifact_status', artifact_status, ...
        'artifact_status_note', ['Execution-status metadata, never a scientific ' ...
            'outcome. COMPLETE requires, for BOTH baselines, that the run ' ...
            'completed the full horizon AND is numerically eligible ' ...
            '(run.completed && run.numerically_eligible). ~numerical_failure ' ...
            'alone is NOT sufficient: numerical eligibility additionally ' ...
            'requires every result-relevant history to be finite. A partial ' ...
            'run stopped by a caught ode45 numerical failure may retain finite ' ...
            'partial diagnostics, but it remains EXECUTION_FAILURE_NUMERICAL ' ...
            'and is never a scientific COMPLETE result.'], ...
        'final_post_run_integrity_note', ['The AUTHORITATIVE post-run integrity ' ...
            'recheck runs AFTER this file was written and hashed, so it cannot ' ...
            'appear here without changing the bytes it describes. It is ' ...
            'returned as identities.post_run_integrity. The ' ...
            'pre_summary_integrity block above is an additional earlier ' ...
            'diagnostic, not that final check.'], ...
        's_cap_wording', p.bl.s_cap_wording, ...
        'harness',       'baseline_evaluate');

    % ---- SUMMARY: written exactly ONCE ------------------------------------
    assert(exist(dest.summary, 'file') ~= 2, 'baseline_evaluate:exists_late', ...
        'ABORT: summary destination appeared during the evaluation: %s', dest.summary);
    save(dest.summary, 'summary', '-v7.3');

    % The summary's OWN identity is returned, not stored inside itself: writing
    % it back would change the bytes it describes. The nominal and APF
    % identities ARE inside the summary, so the saved file names what it
    % accompanies.
    identities.summary = file_identity(dest.summary);
    identities.note = ['Identities of the three final deterministic artifacts. ' ...
        'The nominal and APF identities are also stored inside the summary ' ...
        'file; the summary identity exists only here, to avoid a self-hash ' ...
        'cycle. Each hash was taken immediately after that file''s FINAL write.'];

    fprintf(' summary -> %s\n   sha %s  %d bytes  [%s]\n', dest.summary, ...
        identities.summary.sha256, identities.summary.bytes, artifact_status);

    % ---- FINAL POST-RUN INTEGRITY RECHECK (protocol Sec. 15.4) -------------
    % Ordering is the point: all three final artifacts have now been written
    % FINALLY and hashed, so this recheck certifies every frozen Section-2
    % identity as it stood AFTER the complete evaluation. It lives only in the
    % returned object - putting it inside the summary would require rewriting
    % the summary and would invalidate the hash just taken over it.
    %
    % The three identities are printed ABOVE this call, so if the recheck raises
    % they are still on the record even though the return value is lost.
    identities.post_run_integrity = baseline_preflight(p, postOpt);
    identities.post_run_integrity_note = ['AUTHORITATIVE final postflight, run ' ...
        'AFTER all three final artifacts were written and hashed, per protocol ' ...
        'Sec. 15.4. Covers every frozen Section-2 identity; only the ' ...
        'destination-absence clause is relaxed, because the destinations now ' ...
        'exist by design.'];
    fprintf([' FINAL post-run integrity recheck PASSED: every Section-2 ' ...
        'identity re-verified after all three artifacts were hashed\n']);
    if anyFailure
        fprintf(2, [' NOTE: a baseline had a numerical execution failure; ' ...
            'artifact_status is %s, NOT COMPLETE. This is execution-status ' ...
            'metadata, not a scientific outcome.\n'], artifact_status);
    end
end

% =====================================================================
function [theta, prov] = load_frozen_gains(opt, p, pre, expAgg)
% Verify the tuning record, THEN read the winner out of it. Nothing here
% recomputes or retunes: the only computation is a consistency check that the
% winner the record names really is the eligible candidate it points at.
    f = opt.gain_record;
    gsha = baseline_sha256(f);
    assert(strcmpi(gsha, char(opt.gain_record_sha256)), ...
        'baseline_evaluate:gain_sha', ...
        ['ABORT: the tuning record hashes to\n    %s\nbut the frozen identity ' ...
         'supplied is\n    %s'], gsha, lower(char(opt.gain_record_sha256)));

    G = load(f, 'res');
    assert(isfield(G, 'res'), 'baseline_evaluate:gain_shape', ...
        'The tuning record carries no `res` variable.');
    R = G.res;

    assert(strcmp(R.outcome, 'SEARCH_COMPLETE'), 'baseline_evaluate:gain_outcome', ...
        ['ABORT: the tuning record reports outcome ''%s'', not SEARCH_COMPLETE. ' ...
         'An incomplete or failed search selects no gain set.'], R.outcome);
    assert(strcmpi(R.binding.protocol_sha256, p.bl.protocol_sha256), ...
        'baseline_evaluate:gain_protocol', ...
        ['ABORT: the tuning record was produced under protocol SHA %s, not the ' ...
         'frozen %s.'], R.binding.protocol_sha256, p.bl.protocol_sha256);
    assert(strcmpi(R.binding.aggregate_sha256, expAgg), ...
        'baseline_evaluate:gain_aggregate', ...
        ['ABORT: the tuning record was produced against baseline aggregate %s, ' ...
         'not the frozen %s supplied here.'], R.binding.aggregate_sha256, expAgg);
    assert(strcmpi(R.binding.verification_gate_sha256, ...
                   char(opt.verification_gate_sha256)), ...
        'baseline_evaluate:gain_gate', ...
        ['ABORT: the tuning record was authorised by V1-V11 gate %s, not the ' ...
         'frozen gate %s supplied here.'], R.binding.verification_gate_sha256, ...
        lower(char(opt.verification_gate_sha256)));
    assert(R.n_scenarios == 5, 'baseline_evaluate:gain_scenarios', ...
        'ABORT: the tuning record used %d development scenarios, not 5.', ...
        R.n_scenarios);
    assert(R.Tsim == 800, 'baseline_evaluate:gain_horizon', ...
        'ABORT: the tuning record used Tsim = %g s, not the frozen 800 s.', R.Tsim);

    % ---- the winner must be an ELIGIBLE candidate CONTAINED in the record ---
    assert(isstruct(R.winner) && ~isempty(R.winner), 'baseline_evaluate:winner', ...
        'ABORT: the tuning record carries no selected gain set.');
    ids = [R.candidates.id];
    j = find(ids == R.winner.id, 1);
    assert(~isempty(j), 'baseline_evaluate:winner_absent', ...
        ['ABORT: the record''s winner is id %d, which is not among the %d ' ...
         'candidates the record contains.'], R.winner.id, numel(ids));
    assert(R.candidates(j).eligible, 'baseline_evaluate:winner_ineligible', ...
        ['ABORT: the record''s winner id %d is a numerically INELIGIBLE ' ...
         'candidate; ineligible candidates never enter scientific ranking.'], ...
        R.winner.id);
    assert(isequal(R.candidates(j).levels, R.winner.levels), ...
        'baseline_evaluate:winner_levels', ...
        ['ABORT: the record''s winner levels %s disagree with candidate id %d ' ...
         '(%s).'], mat2str(R.winner.levels), R.winner.id, ...
        mat2str(R.candidates(j).levels));
    assert(isequaln(R.candidates(j).vector, R.winner.vector), ...
        'baseline_evaluate:winner_vector', ...
        ['ABORT: the record''s winner ordering vector disagrees with candidate ' ...
         'id %d.'], R.winner.id);
    assert(isequal(R.candidates(j).round, R.winner.round), ...
        'baseline_evaluate:winner_round', ...
        ['ABORT: the record''s winner reports round %d but candidate id %d was ' ...
         'evaluated in round %d.'], R.winner.round, R.winner.id, ...
        R.candidates(j).round);

    % ---- the winner's theta must BE the stored candidate's theta -----------
    % The winner struct carries a copy of theta. A copy can disagree with the
    % candidate it names, and the gain set that is about to be executed must be
    % the one the search actually evaluated - not a duplicate that drifted.
    tf = {'omega_n', 'zeta', 'beta', 'kappa'};
    for q = 1:numel(tf)
        wv = R.winner.theta.(tf{q});
        cv = R.candidates(j).theta.(tf{q});
        assert(isa(wv, 'double') && isa(cv, 'double') && isequal(wv, cv), ...
            'baseline_evaluate:winner_theta', ...
            ['ABORT: the record''s winner theta.%s = %.17g does not match ' ...
             'candidate id %d theta.%s = %.17g.'], tf{q}, wv, R.winner.id, ...
            tf{q}, cv);
    end

    % ---- the winner must be the STORED TERMINAL INCUMBENT DECISION ---------
    % Replayed from the stored round decisions exactly as BASELINE_TUNING's
    % finish() derived it: the last COMPLETE refinement round's incumbent_after,
    % or the frozen post-coarse incumbent when no refinement round closed.
    % NOTHING IS RERANKED OR RETUNED here - this is stored-state replay only, so
    % that a record whose winner field disagrees with its own search decisions
    % cannot silently supply the evaluation gain set.
    % A SEARCH_COMPLETE record may not contain a half-open round. Every stored
    % round must be COMPLETE: an incomplete round means the search stopped
    % inside a round, so the terminal incumbent it implies was never actually
    % decided under the frozen T1 -> T7 rule.
    if ~isempty(R.rounds)
        completeFlags = logical([R.rounds.complete]);
        assert(all(completeFlags), 'baseline_evaluate:round_incomplete', ...
            ['ABORT: the tuning record reports SEARCH_COMPLETE but round(s) %s ' ...
             'are stored as INCOMPLETE. A record whose search stopped inside a ' ...
             'round has no decided terminal incumbent.'], ...
            mat2str([R.rounds(~completeFlags).index]));

        % Stored round indices must be internally ordered and consistent with a
        % completed search history: 1, 2, ... with no gap, duplicate or
        % reordering, and never more than the frozen maximum of three.
        idxs = [R.rounds.index];
        assert(isequal(idxs, 1:numel(idxs)), 'baseline_evaluate:round_order', ...
            ['ABORT: stored refinement round indices are %s, not the ordered ' ...
             'contiguous sequence 1..%d a completed search produces.'], ...
            mat2str(idxs), numel(idxs));
        assert(numel(idxs) <= 3, 'baseline_evaluate:round_count', ...
            ['ABORT: the tuning record stores %d refinement rounds, above the ' ...
             'frozen maximum of three.'], numel(idxs));
    end

    term = R.coarse_incumbent;
    termSrc = 'frozen post-coarse incumbent (no refinement round closed)';
    if ~isempty(R.rounds)
        term = R.rounds(end).incumbent_after;
        termSrc = sprintf('incumbent_after of the last COMPLETE round (%d)', ...
                          R.rounds(end).index);
    end
    assert(~isempty(term), 'baseline_evaluate:terminal_incumbent', ...
        'ABORT: the tuning record carries no stored terminal incumbent decision.');

    % The stored terminal decision and the record's winner must agree on EVERY
    % identifying quantity, not merely on the id.
    assert(isequal(term.id, R.winner.id), 'baseline_evaluate:winner_not_terminal', ...
        ['ABORT: the record''s winner (id %d) is not the stored terminal ' ...
         'incumbent decision (id %d, from the %s).'], R.winner.id, term.id, termSrc);
    assert(isequal(term.levels, R.winner.levels), ...
        'baseline_evaluate:terminal_levels', ...
        ['ABORT: the stored terminal incumbent levels %s disagree with the ' ...
         'record''s winner levels %s.'], mat2str(term.levels), mat2str(R.winner.levels));
    assert(isequaln(term.vector, R.winner.vector), ...
        'baseline_evaluate:terminal_vector', ...
        'ABORT: the stored terminal incumbent ordering vector disagrees with the winner.');
    assert(isequal(term.round, R.winner.round), ...
        'baseline_evaluate:terminal_round', ...
        ['ABORT: the stored terminal incumbent reports round %d but the ' ...
         'record''s winner reports round %d.'], term.round, R.winner.round);
    for q = 1:numel(tf)
        tv = term.theta.(tf{q});
        wv = R.winner.theta.(tf{q});
        assert(isa(tv, 'double') && isa(wv, 'double') && isequal(tv, wv), ...
            'baseline_evaluate:terminal_theta', ...
            ['ABORT: the stored terminal incumbent theta.%s = %.17g does not ' ...
             'match the record''s winner theta.%s = %.17g.'], tf{q}, tv, tf{q}, wv);
    end

    % The executed gain set is built from the MATCHED CANDIDATE's theta, which
    % every check above was performed against, not from the unchecked duplicate
    % carried in the winner struct.
    cth = R.candidates(j).theta;
    theta = struct('omega_n', cth.omega_n, ...
                   'zeta',    cth.zeta, ...
                   'beta',    cth.beta, ...
                   'kappa',   cth.kappa);

    prov = struct( ...
        'gain_record',              f, ...
        'gain_record_sha256',       gsha, ...
        'outcome',                  R.outcome, ...
        'stop_reason',              R.stop_reason, ...
        'winner_id',                R.winner.id, ...
        'winner_levels',            R.winner.levels, ...
        'winner_vector',            R.winner.vector, ...
        'winner_round',             R.winner.round, ...
        'winner_theta_source',      'matched candidate record (verified equal to winner.theta)', ...
        'terminal_incumbent_source', termSrc, ...
        'n_candidates',             R.n_candidates, ...
        'n_runs',                   R.n_runs, ...
        'n_scenarios',              R.n_scenarios, ...
        'Tsim',                     R.Tsim, ...
        'record_protocol_sha256',   R.binding.protocol_sha256, ...
        'record_aggregate_sha256',  R.binding.aggregate_sha256, ...
        'record_gate_sha256',       R.binding.verification_gate_sha256, ...
        'preflight_protocol_sha256', pre.protocol.sha256, ...
        'note', ['The gain set was READ from the hash-frozen tuning record and ' ...
                 'verified against the candidate it names. Nothing was ' ...
                 'recomputed and nothing was retuned.']);
end

% =====================================================================
function id = file_identity(f)
% SHA-256, byte size and filesystem timestamp of a final artifact, taken
% immediately after its final write.
    d = dir(f);
    assert(~isempty(d), 'baseline_evaluate:identity', ...
        'Cannot take the identity of a missing file: %s', f);
    id = struct( ...
        'file',      f, ...
        'sha256',    baseline_sha256(f), ...
        'bytes',     d(1).bytes, ...
        'datenum',   d(1).datenum, ...
        'timestamp', datestr(d(1).datenum, 'yyyy-mm-dd HH:MM:SS')); %#ok<DATST>
end

% =====================================================================
function c = canonical(d)
% Resolve a directory to a comparable canonical spelling, so that '..'
% segments and separator differences cannot disguise one path as another.
    w = what(d);
    if ~isempty(w)
        c = w(1).path;
    else
        c = d;
    end
    c = strrep(strrep(c, filesep, '/'), char(92), '/');
    if ~isempty(c) && c(end) == '/', c(end) = []; end
end
